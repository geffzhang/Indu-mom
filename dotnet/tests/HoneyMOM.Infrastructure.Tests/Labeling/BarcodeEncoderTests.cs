    [Fact]
    public void DataMatrixMatchesReferenceModules()
    {
        Assert.Equal(
            [
                "101010101010",
                "101100001011",
                "100000110000",
                "101111000011",
                "100010000010",
                "100101110011",
                "111001001110",
                "110110101001",
                "110001011110",
                "101101111101",
                "100010011010",
                "111111111111"
            ],
            ToRows(BarcodeEncoder.EncodeDataMatrix("ABC123", gs1: false)));
    }

    [Fact]
    public void Gs1SeparatorsMatchReferenceModules()
    {
        Assert.Equal(
            "1101001110011110101110110011011001100110110011101101110101110110001111010111011001000100101111011101000110111010001110110110111000101001101110011100101100100111011001100011101011",
            BarcodeEncoder.EncodeCode128("\u001d01012345\u001d10LOT-9", gs1: true));

        Assert.Equal(
            [
                "1010101010101010",
                "1100110111101101",
                "1000100011110110",
                "1011101001101111",
                "1111111111000010",
                "1010100010111111",
                "1000010111100100",
                "1010111010110001",
                "1000101010110110",
                "1011011001010101",
                "1010100101011010",
                "1000000101101011",
                "1010000100010110",
                "1110110110011101",
                "1011100010010010",
                "1111111111111111"
            ],
            ToRows(BarcodeEncoder.EncodeDataMatrix("01012345\u001d10LOT-9", gs1: true)));
    }

    [Fact]
    public void UnsupportedCode128CharacterIsRejected()
    {
        Assert.Throws<ArgumentException>(() => BarcodeEncoder.EncodeCode128("🙂", gs1: false));
    }

    private static string[] ToRows(IReadOnlyList<IReadOnlyList<bool>> matrix) =>
        matrix.Select(row => new string(row.Select(bit => bit ? '1' : '0').ToArray())).ToArray();
}
